import { describe, it, expect, vi } from "vitest";

// A self-hosted instance has its own name and URL. The shared generator
// defaults to lynxprompt.com, so the web wrapper must pass the instance's.
vi.mock("@/lib/feature-flags", () => ({
  APP_NAME: "Acme Rules",
  APP_URL: "https://rules.acme.test",
}));

import { generateAllFiles, generatePlatformFiles } from "@/lib/file-generator";

const config = {
  projectName: "Demo",
  projectDescription: "A demo project",
  languages: [],
  frameworks: [],
  letAiDecide: false,
  repoHost: "",
  repoUrl: "",
  isPublic: true,
  license: "",
  funding: false,
  cicd: [],
  aiBehaviorRules: [],
  additionalFeedback: "",
};

describe("web generator branding", () => {
  it("signs the Cursor rules with the instance's name and URL", () => {
    const [file] = generateAllFiles({ ...config, platform: "cursor" }, {});
    expect(file.content).toContain("*Generated by [Acme Rules](https://rules.acme.test)*");
    expect(file.content).not.toContain("lynxprompt.com");
  });

  it("signs the Tabnine config with the instance's name and URL", () => {
    const [file] = generateAllFiles({ ...config, platform: "tabnine" }, {});
    expect(file.content).toContain("# Generated by Acme Rules - https://rules.acme.test");
  });

  it("brands every file of a multi-platform download", () => {
    const files = generatePlatformFiles(config, {}, ["cursor", "windsurf"]);
    expect(files).toHaveLength(2);
    for (const file of files) expect(file.content).toContain("https://rules.acme.test");
  });
});
